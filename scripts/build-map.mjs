// Draws the "Where we work" map ahead of time, so the site ships plain SVG paths
// (no map library, no Google embed). Re-run after changing countries or sites:
//   node scripts/build-map.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { geoNaturalEarth1, geoPath } from 'd3-geo';
import { feature } from 'topojson-client';

// ISO numeric codes of countries Paul has worked in
const WORKED = { '036': 'Australia', '598': 'Papua New Guinea', '554': 'New Zealand', '682': 'Saudi Arabia', '710': 'South Africa' };

// Sites from the old Google map
const SITES = [
  { name: 'Sunshine Coast', note: 'Home base', lon: 153.119, lat: -26.7965, home: true },
  { name: 'Gympie', lon: 152.6655, lat: -26.1902 },
  { name: 'Parramatta', lon: 151.0017, lat: -33.8148 },
  { name: 'Weipa', lon: 141.8801, lat: -12.6252 },
  { name: 'Tanami Desert', lon: 130.2837, lat: -19.812 },
];

const W = 1000;
const load = (res) => {
  const topo = JSON.parse(readFileSync(new URL(`../node_modules/world-atlas/countries-${res}.json`, import.meta.url)));
  return feature(topo, topo.objects.countries).features.filter((f) => f.id !== '010'); // no Antarctica
};
// Detailed outlines for the highlighted countries, simpler ones for the rest (keeps the file small)
const countries = load('50m');
const background = load('110m');

// Frame the map on the countries worked in, with a little breathing room
const worked = { type: 'FeatureCollection', features: countries.filter((f) => WORKED[f.id]) };
const projection = geoNaturalEarth1().rotate([-100, 0]).fitWidth(W - 40, worked);
const [[x0, y0], [x1, y1]] = geoPath(projection).bounds(worked);
const pad = 20;
projection.translate([projection.translate()[0] - x0 + pad, projection.translate()[1] - y0 + pad]);
const H = Math.round(y1 - y0 + pad * 2);

const path = geoPath(projection).digits(1);
const roughPath = geoPath(projection).digits(0);
const inView = (f) => {
  const [[a, b], [c, d]] = path.bounds(f);
  return c > 0 && a < W && d > 0 && b < H;
};

const land = background.filter((f) => !WORKED[f.id] && inView(f)).map((f) => roughPath(f)).join('');
// One shape per country (some come in pieces), with a label point on its largest piece
const highlighted = Object.entries(WORKED).map(([id, name]) => {
  const parts = countries.filter((f) => f.id === id);
  const d = parts.map((f) => path(f)).join('');
  const biggest = parts
    .flatMap((f) => (f.geometry.type === 'MultiPolygon' ? f.geometry.coordinates : [f.geometry.coordinates]))
    .map((coordinates) => ({ type: 'Polygon', coordinates }))
    .sort((a, b) => path.area(b) - path.area(a))[0];
  const [lx, ly] = path.centroid(biggest);
  return { name, d, label: [Math.round(lx), Math.round(ly)] };
});
const sites = SITES.map(({ lon, lat, ...s }) => {
  const [x, y] = projection([lon, lat]);
  return { ...s, x: +x.toFixed(1), y: +y.toFixed(1) };
});

writeFileSync(
  new URL('../src/components/sections/workMap.data.js', import.meta.url),
  `// Generated by scripts/build-map.mjs. Don't edit by hand.\n` +
  `export const MAP_W = ${W};\nexport const MAP_H = ${H};\n` +
  `export const LAND = ${JSON.stringify(land)};\n` +
  `export const WORKED = ${JSON.stringify(highlighted)};\n` +
  `export const SITES = ${JSON.stringify(sites, null, 2)};\n`
);
console.log('map', W, 'x', H, 'land chars', land.length, 'worked chars', highlighted.reduce((n, c) => n + c.d.length, 0));
